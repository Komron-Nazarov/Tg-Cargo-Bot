def guide_page(kind: str, index: int) -> str:
    pages = CLIENT_GUIDE if kind == "client" else ADMIN_GUIDE if kind == "admin" else ()
    if not 0 <= index < len(pages):
        raise ValueError("Unknown guide page")
    return f"{pages[index]}\n\nСтраница {index + 1}/{len(pages)}"
